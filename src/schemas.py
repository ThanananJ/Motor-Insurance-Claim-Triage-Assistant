"""Validated contracts shared by deterministic and future AI components."""

from __future__ import annotations

from datetime import date
from enum import Enum
from typing import Any, Literal

from pydantic import BaseModel, Field, model_validator


class FactStatus(str, Enum):
    """Explicit tri-state for facts that may not yet be known."""

    TRUE = "true"
    FALSE = "false"
    UNKNOWN = "unknown"


class EventType(str, Enum):
    """Structured event types grounded in the Policy covered-events list."""

    ACCIDENTAL_COLLISION = "accidental_collision"
    THEFT = "theft"
    FIRE = "fire"
    FLOOD = "flood"
    THIRD_PARTY_PROPERTY_DAMAGE = "third_party_property_damage"
    OTHER = "other"
    UNKNOWN = "unknown"


class CoverageAssessment(str, Enum):
    LIKELY_COVERED = "Likely covered"
    POSSIBLY_COVERED = "Possibly covered"
    NOT_COVERED = "Not covered"
    CANNOT_DETERMINE = "Cannot determine"


class Routing(str, Enum):
    STANDARD_PROCESSING = "Standard processing"
    MANUAL_REVIEW = "Manual review"
    FRAUD_REVIEW = "Fraud review"
    REJECTION_REVIEW = "Rejection review"


class ConfidenceLevel(str, Enum):
    HIGH = "High"
    MEDIUM = "Medium"
    LOW = "Low"


class ClaimInput(BaseModel):
    """Assignment claim input fields; free text is data, not rule input."""

    claim_id: str
    customer: str | None = None
    vehicle: str | None = None
    incident_date: date | None = None
    claim_submitted_date: date | None = None
    claim_description: str
    documents_submitted: list[str] = Field(default_factory=list)
    customer_claim_history: str | None = None


class ClaimFacts(BaseModel):
    """Validated semantic facts consumed by deterministic engines.

    A future LLM may propose these values, but it is not a dependency of this
    model or of the deterministic processing flow.
    """

    event_type: EventType = EventType.UNKNOWN
    alcohol_or_drug_involvement: FactStatus = FactStatus.UNKNOWN
    illegal_racing: FactStatus = FactStatus.UNKNOWN
    intentional_damage: FactStatus = FactStatus.UNKNOWN
    outside_permitted_geographic_coverage: FactStatus = FactStatus.UNKNOWN
    late_submission_valid_reason: FactStatus = FactStatus.UNKNOWN
    suspicious_pattern: FactStatus = FactStatus.UNKNOWN
    inconsistent_story: FactStatus = FactStatus.UNKNOWN
    repeated_claims: FactStatus = FactStatus.UNKNOWN
    severe_damage: FactStatus = FactStatus.UNKNOWN
    weak_evidence: FactStatus = FactStatus.UNKNOWN


class LLMExtractionPayload(BaseModel):
    """Flat, strict schema generated by the LLM before canonical conversion.

    The canonical ClaimFacts contract remains the only semantic input to P0.
    This flat boundary avoids asking a small local model to generate a nested
    facts-and-evidence structure in one response.
    """

    event_type: EventType = Field(
        description="Explicit event type; use unknown only when the event is not established."
    )
    alcohol_or_drug_involvement: FactStatus = Field(
        description="true if explicitly involved, false if explicitly ruled out, otherwise unknown."
    )
    illegal_racing: FactStatus = Field(
        description="true if illegal racing is explicit, false if explicitly ruled out, otherwise unknown."
    )
    intentional_damage: FactStatus = Field(
        description="true if intentional damage is explicit, false if explicitly ruled out, otherwise unknown."
    )
    outside_permitted_geographic_coverage: FactStatus = Field(
        description="true or false only from explicit geographic evidence; otherwise unknown."
    )
    late_submission_valid_reason: FactStatus = Field(
        description="true when a valid reason is stated, false when absence of a reason is explicit, otherwise unknown."
    )
    suspicious_pattern: FactStatus = Field(
        description="true only when the supplied claim data explicitly supports a suspicious pattern."
    )
    inconsistent_story: FactStatus = Field(
        description="true only when supplied statements explicitly conflict; otherwise unknown unless consistency is explicit."
    )
    repeated_claims: FactStatus = Field(
        description="true for explicit repeated/multiple claims, false for explicit no prior claims, otherwise unknown."
    )
    severe_damage: FactStatus = Field(
        description="true when severe damage is explicit, false when explicitly described as not severe, otherwise unknown."
    )
    weak_evidence: FactStatus = Field(
        description="true when evidence is explicitly weak or unclear, false when explicitly adequate, otherwise unknown."
    )


