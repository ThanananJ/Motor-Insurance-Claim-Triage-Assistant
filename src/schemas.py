class FactEvidence(BaseModel):
    """Observable input evidence for a proposed semantic fact, not reasoning."""

    fact_name: SemanticFactName
    source: EvidenceSource
    text: str = Field(min_length=1, max_length=500)


class SemanticExtractionPayload(BaseModel):
    """Strict structured payload expected from the semantic LLM."""

    facts: ClaimFacts
    evidence: list[FactEvidence] = Field(default_factory=list)

    @model_validator(mode="before")
    @classmethod
    def require_all_fact_fields(cls, value: Any) -> Any:
        if not isinstance(value, dict):
            return value
        facts = value.get("facts")
        if not isinstance(facts, dict):
            return value
        expected = set(ClaimFacts.model_fields)
        missing = sorted(expected - set(facts))
        if missing:
            raise ValueError(
                "Structured extraction is missing fact fields: " + ", ".join(missing)
            )
        return value


class SemanticExtractionResult(BaseModel):
    """Safe application result; failed extraction always carries unknown facts."""

    success: bool
    facts: ClaimFacts = Field(default_factory=ClaimFacts)
    evidence: list[FactEvidence] = Field(default_factory=list)
    error: str | None = None
    error_code: str | None = None
    provider: str | None = None
    model: str | None = None
    retry_count: int = Field(default=0, ge=0, le=1)


